# Python Loops

# For Loop
print("For Loop:")

for i in range(1, 6):
    print(i)

# While Loop
print("\nWhile Loop:")

count = 1

while count <= 5:
    print(count)
    count += 1

# Loop through a list
print("\nList Loop:")

subjects = ["Python", "AI", "ML"]

for subject in subjects:
    print(subject)
